    /** The action ID part for a device name: lower case, "+" as "plus", other runs of non-letters as "_". */
    static String slug(String name) {
        String s = name.toLowerCase(java.util.Locale.ROOT).replace("+", " plus").replaceAll("[^a-z0-9]+", "_");
        return s.replaceAll("^_+|_+$", "");
    }
